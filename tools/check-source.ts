/**
 * What may not ship, whatever the code around it does.
 *
 *   npm run check:source            this repository
 *   node tools/check-source.ts --root <dir>   another checkout, which is how the control runs it
 *
 * Files tracked by git:
 *
 * 1. **An invisible character.** In a sibling repository a regular expression
 *    meant to hold a word boundary arrived through a shell heredoc as a real
 *    backspace byte, so its gate could never match and passed for days. A
 *    character nobody can see is one nobody can review: a wanted one is written
 *    as an escape.
 * 2. **A path on the machine that wrote it**, which is a leak and a build that
 *    only works there.
 * 3. **A dash used as punctuation** in prose a reader sees: an en or em dash
 *    anywhere, a spaced hyphen in Markdown outside code.
 *
 * Every commit:
 *
 * 4. **The owner is the only author**, and the committer too.
 * 5. **No trailer** crediting anyone else, and no coding tool named in a
 *    message. The build contract says both; a contract nobody checks is a
 *    hope.
 */
import { execFileSync, spawnSync } from 'node:child_process'
import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'

const { values } = parseArgs({ options: { root: { type: 'string' } } })
const root = resolve(values.root ?? resolve(dirname(fileURLToPath(import.meta.url)), '..'))

const OWNER = { name: 'Nikos Broikos', email: 'broikos.nikolaos@gmail.com' }
/*
 * Built from numbers, never typed. At tick 1 this file was written with these
 * classes as \u escapes, and every escape at or above U+00A0 arrived on disk as
 * the literal character it named: the class of invisible characters carried
 * seven of them, and its control's en dash was a real en dash. Its
 * own first run caught both. A code point written as a number cannot be
 * turned into the character by whatever writes the file.
 */
const cp = (...codes: number[]) => String.fromCodePoint(...codes)
const span = (a: number, b: number) => `${cp(a)}-${cp(b)}`
const INVISIBLE = new RegExp(
  `[${span(0x00, 0x08)}${cp(0x0b, 0x0c)}${span(0x0e, 0x1f)}${cp(0x7f, 0xa0, 0xad)}${span(0x2000, 0x200f)}` +
    `${span(0x2028, 0x202f)}${span(0x205f, 0x206f)}${cp(0x3000, 0xfeff)}]`,
  'u',
)
/** In code only: decomposed text is made with normalize('NFD') where a test needs it, so a reader sees the letters. */
const COMBINING = new RegExp(`[${span(0x0300, 0x036f)}]`, 'u')
/** In code only: the Greek question mark and ano teleia, two hyphens and a minus, each the twin of an ASCII character. */
const LOOKALIKE = new RegExp(`[${cp(0x037e, 0x0387, 0x2010, 0x2011, 0x2212)}]`, 'u')
const EN_EM = new RegExp(`[${cp(0x2013, 0x2014)}]`, 'u')
const LOCAL_PATH = /[A-Za-z]:[\\/](?:Users|xampp|Windows)\b|\/(?:home|Users)\/[a-z]/i
const SPACED_HYPHEN = / -{1,2} /
const TRAILER = /^(co-authored-by|signed-off-by|generated with|generated by)\b/im
const TOOLS = /\b(claude|anthropic|copilot|cursor|codex|windsurf|devin|aider|chatgpt)\b/i

const git = (...args: string[]) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8' })

const fails: string[] = []

// tracked and untracked alike, ignored files aside: a file not yet added is the next commit's file
const files = git('ls-files', '-z', '--cached', '--others', '--exclude-standard').split('\0').filter(Boolean)
for (const rel of files) {
  if (/\.(png|jpg|gif|webm|mp4|woff2?|ico|sqlite|gz)$/i.test(rel)) continue
  const text = readFileSync(resolve(root, rel), 'utf8')
  const self = rel === 'tools/check-source.ts'
  const prose = rel.endsWith('.md')
  const code = /\.(ts|mts|mjs|js)$/.test(rel)
  let inFence = false
  text.split('\n').forEach((line, i) => {
    const at = `${rel}:${i + 1}`
    if (INVISIBLE.test(line)) fails.push(`${at} carries an invisible character: build it from its code point`)
    if (code && COMBINING.test(line)) fails.push(`${at} carries a combining mark: make decomposed text with normalize('NFD')`)
    if (code && LOOKALIKE.test(line)) fails.push(`${at} carries a twin of an ASCII character: build it from its code point`)
    if (self) return // this file names the patterns it looks for
    if (LOCAL_PATH.test(line)) fails.push(`${at} names a path on this machine`)
    if (EN_EM.test(line)) fails.push(`${at} has an en or em dash`)
    if (prose && /^\s*```/.test(line)) inFence = !inFence
    if (prose && !inFence && SPACED_HYPHEN.test(line.replace(/`[^`]*`/g, ''))) fails.push(`${at} uses a hyphen as a dash`)
  })
}

const SEP = '\u001e'
const hasCommits = spawnSync('git', ['-C', root, 'rev-parse', '--verify', '-q', 'HEAD']).status === 0
const log = hasCommits ? git('log', `--format=%H%x1f%an%x1f%ae%x1f%cn%x1f%ce%x1f%B${SEP}`) : ''
const commits = log.split(SEP).map((c) => c.trim()).filter(Boolean)
for (const c of commits) {
  const [hash, an, ae, cn, ce, body] = c.split('\u001f')
  const at = `commit ${hash.slice(0, 7)}`
  if (an !== OWNER.name || ae !== OWNER.email) fails.push(`${at} is authored by ${an} <${ae}>`)
  if (cn !== OWNER.name || ce !== OWNER.email) fails.push(`${at} is committed by ${cn} <${ce}>`)
  if (TRAILER.test(body)) fails.push(`${at} carries a trailer: ${body.match(TRAILER)![0]}`)
  if (TOOLS.test(body)) fails.push(`${at} names a coding tool: ${body.match(TOOLS)![0]}`)
  if (EN_EM.test(body) || SPACED_HYPHEN.test(body)) fails.push(`${at} uses a dash as punctuation in its message`)
}

if (fails.length) {
  console.error(fails.map((f) => 'FAIL  ' + f).join('\n'))
  process.exit(1)
}
console.log(`check:source ok: ${files.length} files and ${commits.length} commits; no invisible character, no local path, no dash as punctuation, one author, no trailer, no tool named`)
